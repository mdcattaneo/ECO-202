# Randomized experiments, causal effects, and the jtrain2 assignment

# Create names for the six fictional experimental units.
unit <- c("A", "B", "C", "D", "E", "F")

# Enter the six untreated potential outcomes from Board work 1.
y0 <- c(4, 6, 2, 5, 3, 8)

# Enter the six treated potential outcomes from Board work 1.
y1 <- c(7, 7, 4, 6, 5, 8)

# Calculate each unit's individual treatment effect.
individual_effect <- y1 - y0

# Calculate the fixed finite-sample average treatment effect.
average_treatment_effect <- mean(individual_effect)

# Display the complete fictional potential-outcome table.
print(data.frame(unit, y0, y1, individual_effect))

# Display the finite-sample average treatment effect.
cat("Finite-sample ATE:", average_treatment_effect, "\n")

# List every possible assignment of three of the six units to treatment.
possible_treated_groups <- combn(1:6, 3)

# Create an empty vector for the twenty difference-in-means estimates.
estimated_effect <- numeric(ncol(possible_treated_groups))

# Begin a simple loop over the twenty possible assignments.
for (assignment_number in 1:ncol(possible_treated_groups)) {
  # Start with every unit assigned to control.
  assignment <- rep(0, 6)

  # Assign the three selected units to treatment.
  assignment[possible_treated_groups[, assignment_number]] <- 1

  # Construct the observed outcome under this assignment.
  observed_outcome <- assignment * y1 + (1 - assignment) * y0

  # Calculate the treated-minus-control difference in observed means.
  estimated_effect[assignment_number] <- mean(observed_outcome[assignment == 1]) - mean(observed_outcome[assignment == 0])

  # End this assignment repetition.
}

# Display all twenty possible difference-in-means estimates.
print(estimated_effect)

# Verify that the randomization average equals the finite-sample ATE.
cat("Average estimate across all assignments:", mean(estimated_effect), "\n")

# Display the smallest and largest estimates generated by valid assignments.
cat("Range across assignments:", range(estimated_effect), "\n")

# Open a PNG file for the randomization-distribution figure.
png("figures/six-unit-randomization-distribution.png", width = 1200, height = 760, res = 140)

# Plot the sorted estimates from the twenty assignments.
plot(sort(estimated_effect), pch = 19, col = "steelblue4", xlab = "Assignment after sorting by its estimate", ylab = "Treated-minus-control difference", main = "Chance variation across all 20 valid assignments", xaxt = "n")

# Add an axis that numbers the sorted assignments from one through twenty.
axis(1, at = 1:20, labels = 1:20)

# Add a horizontal line at the fixed finite-sample ATE.
abline(h = average_treatment_effect, col = "firebrick3", lwd = 3, lty = 2)

# Explain the horizontal reference line inside the figure.
legend("topleft", legend = "Finite-sample ATE = 1.5", col = "firebrick3", lwd = 3, lty = 2, bty = "n")

# Close the PNG file.
dev.off()

